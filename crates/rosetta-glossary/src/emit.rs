//! Deterministic adapters for existing prose and rule tooling.

use std::collections::BTreeMap;

use serde::Serialize;

use super::model::{Glossary, TermStatus};
use super::query;

pub const VALE_STYLE: &str = ".vale/styles/Rosetta";
pub const VALE_ACCEPT: &str = ".vale/styles/config/vocabularies/Rosetta/accept.txt";
pub const WHETSTONE_QUERY: &str = ".rosetta/emit/whetstone.scm";
pub const WORD_LIST: &str = ".rosetta/emit/words.json";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Target {
    Vale,
    Whetstone,
    Json,
}

#[derive(Serialize)]
struct WordList<'a> {
    schema: &'static str,
    terms: Vec<WordTerm<'a>>,
}

#[derive(Serialize)]
struct WordTerm<'a> {
    id: &'a str,
    name: &'a str,
    avoid: Vec<WordAvoid<'a>>,
}

#[derive(Serialize)]
struct WordAvoid<'a> {
    word: &'a str,
    except: &'a [String],
}

/// The paths are fixed so `glossary check` can find committed exports without
/// trusting a second manifest. Callers decide when to write the files.
pub fn files(
    glossary: &Glossary,
    target: Target,
) -> Result<BTreeMap<String, String>, serde_json::Error> {
    let settled = glossary
        .terms
        .iter()
        .filter(|term| term.status == TermStatus::Settled)
        .collect::<Vec<_>>();
    let mut result = BTreeMap::new();
    match target {
        Target::Vale => {
            let names = settled
                .iter()
                .map(|term| regex::escape(&term.name))
                .collect::<Vec<_>>();
            result.insert(VALE_ACCEPT.to_owned(), format!("{}\n", names.join("\n")));
            for term in settled {
                if term.avoid_words().is_empty() {
                    continue;
                }
                let mut text = String::from(
                    "# Generated by Rosetta from the glossary.\nextends: substitution\nlevel: warning\nmessage: \"Use '%s' instead of '%s'.\"\nignorecase: true\n",
                );
                let exceptions = term
                    .avoid_words()
                    .iter()
                    .flat_map(|avoid| avoid.except.as_deref().unwrap_or_default())
                    .collect::<Vec<_>>();
                if !exceptions.is_empty() {
                    text.push_str("exceptions:\n");
                    for phrase in exceptions {
                        text.push_str(&format!("  - {}\n", yaml_string(phrase)?));
                    }
                }
                text.push_str("swap:\n");
                for avoid in term.avoid_words() {
                    // Vale treats swap keys as regexes. Mirror the plural rule
                    // used by the built-in linter, without treating punctuation
                    // in a word as regex syntax.
                    let pattern = format!("{}s?", regex::escape(&avoid.word));
                    text.push_str(&format!(
                        "  {}: {}\n",
                        yaml_string(&pattern)?,
                        yaml_string(&term.name)?
                    ));
                }
                let id = term.id.strip_prefix("term.").unwrap_or(&term.id);
                result.insert(format!("{VALE_STYLE}/Term-{id}.yml"), text);
            }
        }
        Target::Whetstone => {
            result.insert(
                WHETSTONE_QUERY.to_owned(),
                query::glossary_query(glossary).unwrap_or_default(),
            );
        }
        Target::Json => {
            let terms = settled
                .iter()
                .map(|term| WordTerm {
                    id: &term.id,
                    name: &term.name,
                    avoid: term
                        .avoid_words()
                        .iter()
                        .map(|avoid| WordAvoid {
                            word: &avoid.word,
                            except: avoid.except.as_deref().unwrap_or_default(),
                        })
                        .collect(),
                })
                .collect();
            let list = WordList {
                schema: "rosetta.word-list/v1",
                terms,
            };
            result.insert(
                WORD_LIST.to_owned(),
                serde_json::to_string_pretty(&list)? + "\n",
            );
        }
    }
    Ok(result)
}

fn yaml_string(value: &str) -> Result<String, serde_json::Error> {
    serde_json::to_string(value)
}
