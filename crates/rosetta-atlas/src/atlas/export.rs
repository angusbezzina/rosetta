//! A compact, checked Markdown projection of the same atlas bundle as the viewer.

use std::fmt::Write;
use std::path::Path;

use super::bundle::Bundle;
use super::model::NodeKind;
use super::{AtlasLoadError, blurb, bundle_repo_from};

pub const ATLAS_OUTPUT: &str = "ATLAS.md";

fn cell(text: &str) -> String {
    text.replace(['\n', '\r'], " ").replace('|', "\\|")
}

fn purpose(root: &Path) -> Option<String> {
    let readme = std::fs::read_to_string(root.join("README.md")).ok()?;
    blurb::of_file("README.md", &readme)
}

/// The default focus of each view. A connections view has many possible
/// roots; this page shows one and names that limitation.
pub fn render_markdown(bundle: &Bundle, purpose: Option<&str>) -> String {
    render_markdown_for(bundle, purpose, ".rosetta/atlas.json")
}

pub fn render_markdown_for(bundle: &Bundle, purpose: Option<&str>, source: &str) -> String {
    let mut page = format!(
        "<!-- Generated by rosetta atlas export from {source}. Edit the source, then export again. -->\n\n# {} Atlas\n\n",
        bundle.project.name
    );
    match purpose {
        Some(purpose) => {
            let _ = writeln!(page, "From README.md: {purpose}\n");
        }
        None => page.push_str("Project purpose has not been curated yet.\n\n"),
    }
    page.push_str("This page shows the default focus of each view. Choose a part in the local viewer for its own connections and evidence.\n\n");
    for view in &bundle.views {
        let _ = writeln!(page, "## {}\n", view.title.replace(['\n', '\r'], " "));
        if !view.description.is_empty() {
            let _ = writeln!(page, "{}\n", view.description);
        }
        let selected = view
            .sources
            .get(&view.default_root)
            .map(|source| (view.default_root.as_str(), source))
            .or_else(|| {
                view.sources
                    .iter()
                    .next()
                    .map(|(root, source)| (root.as_str(), source))
            });
        if let Some((root, source)) = selected {
            if !root.is_empty() {
                let _ = writeln!(page, "Focus: `{root}`.\n");
            }
            page.push_str("```mermaid\n");
            page.push_str(&super::page::without_clicks(source));
            page.push_str("```\n\n");
        } else {
            page.push_str("No diagram is available for this view yet.\n\n");
        }
    }
    page.push_str("## Parts\n\n");
    page.push_str("| ID | Part | Family | Tier | Path | Summary | Last change |\n");
    page.push_str("| --- | --- | --- | --- | --- | --- | --- |\n");
    let mut parts: Vec<_> = bundle
        .nodes
        .iter()
        .filter(|node| {
            node.kind.is_part()
                || matches!(
                    node.kind,
                    NodeKind::Crate | NodeKind::Package | NodeKind::App | NodeKind::Resource
                )
        })
        .collect();
    parts.sort_by(|a, b| a.id.cmp(&b.id));
    for node in parts {
        let tier = node.tier.map_or("", |tier| tier.as_str());
        let updated = node
            .updated
            .as_ref()
            .map_or("", |updated| updated.at.as_str());
        let _ = writeln!(
            page,
            "| {} | {} | {} | {} | {} | {} | {} |",
            cell(&node.id),
            cell(&node.label),
            node.family.as_str(),
            tier,
            cell(node.path.as_deref().unwrap_or("")),
            cell(node.summary.as_deref().unwrap_or("")),
            updated
        );
    }
    page
}

pub fn expected(root: &Path) -> Result<String, AtlasLoadError> {
    expected_from(root, crate::repo::SOURCE_DIR)
}

pub fn expected_from(root: &Path, source_dir: &str) -> Result<String, AtlasLoadError> {
    Ok(render_markdown_for(
        &bundle_repo_from(root, source_dir)?,
        purpose(root).as_deref(),
        &format!("{source_dir}/atlas.json"),
    ))
}

/// Write ATLAS.md only when its contents have changed.
pub fn export_repo(root: &Path) -> Result<bool, AtlasLoadError> {
    export_repo_from(root, crate::repo::SOURCE_DIR)
}

pub fn export_repo_from(root: &Path, source_dir: &str) -> Result<bool, AtlasLoadError> {
    let text = expected_from(root, source_dir)?;
    let path = root.join(ATLAS_OUTPUT);
    if std::fs::read_to_string(&path).ok().as_deref() == Some(&text) {
        return Ok(false);
    }
    std::fs::write(path, text).map_err(|source| AtlasLoadError::Io {
        path: ATLAS_OUTPUT.to_owned(),
        source,
    })?;
    Ok(true)
}
