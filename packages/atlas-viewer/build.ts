#!/usr/bin/env bun
/** Build the framework-free standalone viewer served by `rosetta atlas open`. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const PKG = import.meta.dir;
const DIST = join(PKG, "dist");
const VENDORED = join(PKG, "../../crates/rosetta-atlas/viewer-dist");
const CHECK = Bun.argv.includes("--check");
const VENDOR = Bun.argv.includes("--vendor");
const PELE = Bun.resolveSync("pele", PKG);
const OUTPUTS = ["atlas-viewer.js", "pele.js", "atlas-viewer.css", "index.html", "site-viewer.js", "site-index.html"] as const;

async function script(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(PKG, "src/standalone.ts")],
    format: "esm",
    target: "browser",
    minify: true,
    plugins: [{
      name: "pele-external",
      setup(build) {
        build.onResolve({ filter: /^pele$/ }, () => ({ path: "pele", namespace: "pele-external" }));
        build.onLoad({ filter: /.*/, namespace: "pele-external" }, () => ({
          contents: 'export { mount, parse, render } from "./pele.js";',
          loader: "js",
        }));
        build.onResolve({ filter: /^\.\/pele\.js$/ }, () => ({ path: "./pele.js", external: true }));
      },
    }],
  });
  if (!result.success) throw new AggregateError(result.logs, "atlas viewer build failed");
  const output = result.outputs[0];
  if (!output) throw new Error("atlas viewer build wrote nothing");
  return `// GENERATED by packages/atlas-viewer/build.ts. Do not edit.\n${await output.text()}`;
}

async function siteScript(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(PKG, "src/site.ts")],
    format: "iife",
    target: "browser",
    minify: true,
  });
  if (!result.success) throw new AggregateError(result.logs, "atlas site build failed");
  const output = result.outputs[0];
  if (!output) throw new Error("atlas site build wrote nothing");
  return `// GENERATED by packages/atlas-viewer/build.ts. Do not edit.\n${await output.text()}`;
}

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Rosetta Atlas</title>
<link rel="stylesheet" href="./atlas-viewer.css">
<style>html,body{height:100%;margin:0}body{display:flex;flex-direction:column}#atlas{flex:1;min-height:0}</style>
</head>
<body>
<nav id="focus-bar" class="rosetta-focus-bar" aria-label="Focused view" hidden></nav>
<main id="atlas"></main>
<script type="module">import { boot } from "./atlas-viewer.js"; boot(document.getElementById("atlas"));</script>
</body>
</html>
`;

const sitePage = page
  .replace('<script type="module">import { boot } from "./atlas-viewer.js"; boot(document.getElementById("atlas"));</script>',
    '<script>__ROSETTA_INLINE_DATA__</script>\n<script src="./site-viewer.js" defer></script>');

async function build() {
  return {
    "atlas-viewer.js": await script(),
    "pele.js": await readFile(PELE, "utf8"),
    "atlas-viewer.css": `/* GENERATED by packages/atlas-viewer/build.ts. Do not edit. */\n${await readFile(join(PKG, "src/tokens.css"), "utf8")}\n${await readFile(join(PKG, "src/styles.css"), "utf8")}`,
    "index.html": page,
    "site-viewer.js": await siteScript(),
    "site-index.html": sitePage,
  } satisfies Record<(typeof OUTPUTS)[number], string>;
}

if (import.meta.main) {
  const files = await build();
  if (CHECK) {
    const stale = [];
    for (const directory of VENDOR ? [DIST, VENDORED] : [DIST]) {
      for (const name of OUTPUTS) {
        if ((await readFile(join(directory, name), "utf8").catch(() => "")) !== files[name]) stale.push(`${directory === DIST ? "dist" : "vendored"}/${name}`);
      }
    }
    if (stale.length > 0) {
      console.error(`atlas viewer dist is stale: ${stale.join(", ")}`);
      process.exit(1);
    }
    console.log("atlas viewer dist matches sources");
  } else {
    await mkdir(DIST, { recursive: true });
    for (const name of OUTPUTS) await writeFile(join(DIST, name), files[name]);
    if (VENDOR) {
      await mkdir(VENDORED, { recursive: true });
      for (const name of OUTPUTS) await writeFile(join(VENDORED, name), files[name]);
    }
    console.log(`atlas viewer wrote ${OUTPUTS.length} files${VENDOR ? " and vendored copies" : ""}`);
  }
}
